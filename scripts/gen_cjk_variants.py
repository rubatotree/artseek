"""Generate the CJK equal-character table used for fuzzy name search.

The table groups characters that users treat as "the same character" when
typing a search query: simplified/traditional pairs (宫/宮), regional variants
(裡/裏, 峰/峯) and Japanese shinjitai/kyuujitai pairs (沢/澤, 髪/髮). Every
group folds to a single representative so that a query typed in any script
form still matches.

Source data: OpenCC 1.x dictionaries (Apache-2.0),
https://github.com/BYVoid/OpenCC — ``TSCharacters``, ``TWVariants``,
``HKVariants``, ``JPShinjitaiCharacters``, ``CJK_Compatibility_Ideographs``.

Usage:
    python scripts/gen_cjk_variants.py
    python scripts/gen_cjk_variants.py --cache-dir D:/tmp/opencc
"""

from __future__ import annotations

import argparse
import sys
import urllib.request
from pathlib import Path

BASE_URL = "https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary"
SOURCES = (
    "CJK_Compatibility_Ideographs",
    "TSCharacters",
    "TWVariants",
    "HKVariants",
    "JPShinjitaiCharacters",
)

# Variants that no OpenCC table covers but that show up in illustrator names.
# Left side is folded into the right side; groups are merged transitively.
SUPPLEMENT = (
    ("髙", "高"),
    ("﨑", "崎"),
    ("嵜", "崎"),
    ("濵", "浜"),
    ("邉", "邊"),
    ("舘", "館"),
    ("嶋", "島"),
    ("嶌", "島"),
    ("德", "徳"),
    ("惠", "恵"),
    ("壽", "寿"),
    ("淸", "清"),
    ("靑", "青"),
    ("槇", "槙"),
    ("凜", "凛"),
)

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "artseek" / "core" / "cjk_variants.py"


def _fetch(name: str, cache_dir: Path) -> str:
    path = cache_dir / f"{name}.txt"
    if not path.exists():
        cache_dir.mkdir(parents=True, exist_ok=True)
        url = f"{BASE_URL}/{name}.txt"
        print(f"download {url}", file=sys.stderr)
        with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310
            path.write_text(response.read().decode("utf-8"), encoding="utf-8")
    return path.read_text(encoding="utf-8")


def _pairs(text: str) -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, _, values = line.partition("\t")
        key = key.strip()
        if len(key) != 1:
            continue
        for value in values.split():
            if len(value) == 1 and value != key:
                pairs.append((key, value))
    return pairs


class _Union:
    def __init__(self) -> None:
        self.parent: dict[str, str] = {}

    def find(self, item: str) -> str:
        parent = self.parent.setdefault(item, item)
        while parent != item:
            self.parent[item] = self.parent.get(parent, parent)
            item = parent
            parent = self.parent[item]
        return item

    def union(self, left: str, right: str) -> None:
        root_left, root_right = self.find(left), self.find(right)
        if root_left != root_right:
            self.parent[root_right] = root_left


def _keep(char: str) -> bool:
    code = ord(char)
    return (
        0x3400 <= code <= 0x4DBF
        or 0x4E00 <= code <= 0x9FFF
        or 0xF900 <= code <= 0xFAFF
    )


def build(cache_dir: Path) -> list[str]:
    union = _Union()
    for name in SOURCES:
        for left, right in _pairs(_fetch(name, cache_dir)):
            if _keep(left) and _keep(right):
                union.union(left, right)
    for left, right in SUPPLEMENT:
        union.union(left, right)

    groups: dict[str, list[str]] = {}
    for char in list(union.parent):
        groups.setdefault(union.find(char), []).append(char)

    merged: list[str] = []
    for members in groups.values():
        if len(members) < 2:
            continue
        # Prefer a BMP glyph as the folded representative so keys stay in the
        # Basic Multilingual Plane and render on every font.
        members.sort()
        merged.append("".join(members))
    merged.sort()
    return merged


def render(groups: list[str]) -> str:
    lines = [
        '"""CJK variant equivalence groups used for simplified/traditional folding.',
        "",
        "Generated by ``scripts/gen_cjk_variants.py`` from the OpenCC dictionaries",
        "(Apache-2.0, https://github.com/BYVoid/OpenCC) plus a curated supplement.",
        "Every character inside one group is treated as the same character for",
        "search; the group is stored as a plain string, the first character being",
        "the folded representative. Do not edit by hand.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "GROUPS: tuple[str, ...] = (",
    ]
    for group in groups:
        if '"' in group or "\\" in group:
            raise ValueError(f"unexpected character in group: {group!r}")
        lines.append(f'    "{group}",')
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--cache-dir",
        type=Path,
        default=Path(__file__).resolve().parent / ".opencc-cache",
        help="where to cache the downloaded OpenCC dictionaries",
    )
    args = parser.parse_args()
    groups = build(args.cache_dir)
    OUTPUT.write_text(render(groups), encoding="utf-8", newline="\n")
    chars = sum(len(group) for group in groups)
    print(f"wrote {OUTPUT} — {len(groups)} groups, {chars} characters")


if __name__ == "__main__":
    main()
